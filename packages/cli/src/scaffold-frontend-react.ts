function hooksOf(entity: NormalizedEntity): string {
  const n = namesOf(entity);
  const lines = [
    "",
    `export const ${n.camel}Keys = {`,
    `  all: [${str(n.kebab)}] as const,`,
    `  list: (query: ${n.pascal}Query) => [${str(n.kebab)}, "list", query] as const,`,
    "};",
    "",
    `/** 列表查询：翻页时保留上一页数据，避免表格闪空（设计规范 CACHE.SWR）。 */`,
    `export function use${n.pascal}List(query: ${n.pascal}Query) {`,
    `  return useQuery({ queryKey: ${n.camel}Keys.list(query), queryFn: ({ signal }) => ${n.api}.list(query, signal), placeholderData: keepPreviousData });`,
    "}",
  ];
  if (has(entity, "create") || has(entity, "update")) {
    const mutation =
      has(entity, "create") && has(entity, "update")
        ? `input.id === undefined ? ${n.api}.create(input.body) : ${n.api}.update(input.id, { ...input.body, version: input.version ?? 0 })`
        : has(entity, "update")
          ? `${n.api}.update(input.id ?? 0, { ...input.body, version: input.version ?? 0 })`
          : `${n.api}.create(input.body)`;
    lines.push(
      "",
      `export interface Save${n.pascal}Input {`,
      "  readonly id?: number;",
      "  readonly version?: number;",
      `  readonly body: ${n.pascal}Write;`,
      "}",
      "",
      `/** 新建或修改：成功后让这个资源的所有查询失效（设计规范 CACHE.INVALIDATE）。 */`,
      `export function useSave${n.pascal}() {`,
      "  const client = useQueryClient();",
      "  return useMutation({",
      `    mutationFn: (input: Save${n.pascal}Input) => ${mutation},`,
      `    onSettled: () => client.invalidateQueries({ queryKey: ${n.camel}Keys.all }),`,
      "  });",
      "}",
    );
  }
  if (has(entity, "delete")) {
    lines.push(
      "",
      `export function useRemove${n.pascal}() {`,
      "  const client = useQueryClient();",
      "  return useMutation({",
      `    mutationFn: (record: { readonly id: number; readonly version: number }) => ${n.api}.remove(record.id, record.version),`,
      `    onSettled: () => client.invalidateQueries({ queryKey: ${n.camel}Keys.all }),`,
      "  });",
      "}",
    );
  }
  lines.push("");
  return lines.join("\n");
}

function renderApi(entity: NormalizedEntity): string {
  const imports = ["keepPreviousData", "useQuery"];
  if (has(entity, "create") || has(entity, "update") || has(entity, "delete")) imports.push("useMutation", "useQueryClient");
  const client = renderApiClient(entity, HEADER, [`import { ${imports.sort().join(", ")} } from "@tanstack/react-query";`]);
  return `${client.trimEnd()}\n${hooksOf(entity)}`;
}

function cellJsx(field: NormalizedField, camel: string): string {
  const value = `record.${field.property}`;
  switch (field.type) {
    case "enum":
      return `{${value} == null ? EMPTY : t(\`${camel}.enums.${field.property}.\${${value}}\`)}`;
    case "decimal":
      return `{formatDecimal(${value}, ${field.scale ?? 0})}`;
    case "int":
    case "long":
      return `{formatNumber(${value})}`;
    case "date":
      return `{formatDate(${value})}`;
    case "datetime":
      return `{formatDateTime(${value})}`;
    case "bool":
      return `<Checkbox checked={${value} === true} disabled aria-label={t("${camel}.fields.${field.property}")} />`;
    default:
      return `{${value} ?? EMPTY}`;
  }
}

function valuesConst(field: NormalizedField): string {
  return `${field.property.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase()}_VALUES`;
}

function numeric(field: NormalizedField): boolean {
  return field.type === "int" || field.type === "long" || field.type === "decimal";
}

function formatNames(columns: readonly NormalizedField[]): string[] {
  const names = new Set<string>(["formatDateTime"]);
  for (const field of columns) {
    if (field.type === "decimal") names.add("formatDecimal");
    else if (field.type === "int" || field.type === "long") names.add("formatNumber");
    else if (field.type === "date") names.add("formatDate");
    else if (field.type === "datetime") names.add("formatDateTime");
    else if (field.type !== "bool") names.add("EMPTY");
  }
  return [...names].sort();
}

