#!/usr/bin/env node
// 把 React 画廊（packages/studio-react）里管理侧前端用到的 Geist 组件源码与主题样式，同步成脚手架的种子素材
// （packages/cli/src/scaffold-geist-assets.generated.ts）。React 管理侧外壳的种子从这里取，画廊与生成的项目
// 用同一份组件实现；scaffold-frontend-shell.spec 核对两边一致，漏同步会红。
//
// 用法：node scripts/sync-geist-shell.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

/** React 模板用到的组件（与 scaffold-frontend-react.ts 的 import 一一对应）。 */
export const GEIST_SHELL_COMPONENTS = ["alert", "button", "dialog", "input", "label", "popover", "select", "table"];

/**
 * 画廊的 geist.css 只在 .geist-root 里做 preflight、只扫规范页；项目里要全局生效。取它的主题变量（:root 与
 * @theme inline）和排版类，换成全局的 Tailwind 入口与正文底色。
 */
export function deriveGlobalsCss(geistCss) {
  const rootStart = geistCss.indexOf(":root {");
  const themeStart = geistCss.indexOf("@theme inline {", rootStart);
  const themeEnd = geistCss.indexOf("\n}\n", themeStart);
  const typeStart = geistCss.indexOf("/* Geist 排版类");
  if (rootStart < 0 || themeStart < 0 || themeEnd < 0 || typeStart < 0) throw new Error("geist.css 结构变了：找不到 :root / @theme inline / 排版类");
  return [
    "/* Geist 主题（pomaster scaffold 只在第一次生成时写这个文件，之后归项目所有）。",
    " * 主题变量与排版类取自 pomaster 的 React · Geist 画廊（packages/studio-react/src/styles/geist.css）。 */",
    '@import "tailwindcss";',
    '@import "tw-animate-css";',
    "",
    geistCss.slice(rootStart, themeEnd + 2).trimEnd(),
    "",
    "@layer base {",
    "  body {",
    "    background-color: var(--background);",
    "    color: var(--foreground);",
    "    font-family: var(--font-sans);",
    "  }",
    "}",
    "",
    geistCss.slice(typeStart).trimEnd(),
    "",
  ].join("\n");
}

export function readShellAssets(repo) {
  const studio = join(repo, "packages", "studio-react", "src");
  const files = {};
  for (const name of GEIST_SHELL_COMPONENTS) files[`components/ui/${name}.tsx`] = readFileSync(join(studio, "components", "ui", `${name}.tsx`), "utf8");
  files["lib/utils.ts"] = readFileSync(join(studio, "lib", "utils.ts"), "utf8");
  return { files, globalsCss: deriveGlobalsCss(readFileSync(join(studio, "styles", "geist.css"), "utf8")) };
}

export function renderAssetsModule(assets) {
  return [
    "// GENERATED by scripts/sync-geist-shell.mjs —— 不要手改，改画廊（packages/studio-react）后重跑同步。",
    "// React 管理侧外壳的种子素材：画廊里的 Geist 组件源码与主题样式。",
    "",
    `export const GEIST_SHELL_FILES: Readonly<Record<string, string>> = ${JSON.stringify(assets.files, null, 2)};`,
    "",
    `export const GEIST_GLOBALS_CSS = ${JSON.stringify(assets.globalsCss)};`,
    "",
  ].join("\n");
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const repo = resolve(dirname(fileURLToPath(import.meta.url)), "..");
  const target = join(repo, "packages", "cli", "src", "scaffold-geist-assets.generated.ts");
  writeFileSync(target, renderAssetsModule(readShellAssets(repo)));
  console.log(`wrote ${target}`);
}
