export function tableColumns(entity: NormalizedEntity): NormalizedField[] {
  return businessFields(entity)
    .filter((field) => field.type !== "text" && field.classification !== "sensitive_pii")
    .slice(0, 7);
}

function cellExpression(field: NormalizedField, camel: string): string | null {
  switch (field.type) {
    case "enum":
      return `record.${field.property} == null ? EMPTY : t(\`${camel}.enums.${field.property}.\${record.${field.property}}\`)`;
    case "decimal":
      return `formatDecimal(record.${field.property}, ${field.scale ?? 0})`;
    case "int":
    case "long":
      return `formatNumber(record.${field.property})`;
    case "date":
      return `formatDate(record.${field.property})`;
    case "datetime":
      return `formatDateTime(record.${field.property})`;
    case "bool":
      return null;
    default:
      return `record.${field.property} ?? EMPTY`;
  }
}

function formatImports(columns: readonly NormalizedField[]): string {
  const names = new Set<string>(["formatDateTime"]);
  for (const field of columns) {
    if (field.type === "decimal") names.add("formatDecimal");
    else if (field.type === "int" || field.type === "long") names.add("formatNumber");
    else if (field.type === "date") names.add("formatDate");
    else if (field.type === "datetime") names.add("formatDateTime");
    else if (field.type !== "bool") names.add("EMPTY");
  }
  return [...names].sort().join(", ");
}

