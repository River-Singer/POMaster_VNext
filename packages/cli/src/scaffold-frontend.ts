export function kebab(key: string): string {
  return key.replace(/_/g, "-");
}

export function adminEntities(spec: NormalizedDomainSpec): NormalizedEntity[] {
  return spec.surfaces.admin === undefined ? [] : spec.entities.filter((entity) => entity.exposure.admin !== undefined);
}

export function businessFields(entity: NormalizedEntity): NormalizedField[] {
  const keys = entity.exposure.admin?.fields ?? [];
  return entity.fields.filter((field) => !field.system && keys.includes(field.key));
}

export function has(entity: NormalizedEntity, operation: string): boolean {
  return entity.exposure.admin?.operations.includes(operation) === true;
}

export function tsType(field: NormalizedField): string {
  switch (field.type) {
    case "int":
    case "long":
      return "number";
    case "bool":
      return "boolean";
    case "enum":
      return (field.values ?? []).map((value) => JSON.stringify(value.key)).join(" | ") || "string";
    default:
      return "string";
  }
}

export function str(value: string): string {
  return JSON.stringify(value);
}

