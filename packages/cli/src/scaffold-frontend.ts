function formItem(field: NormalizedField, camel: string): string {
  const label = `:label="t('${camel}.fields.${field.property}')"`;
  const head = `      <a-form-item ${label} name="${field.property}">`;
  let control: string;
  switch (field.type) {
    case "text":
      control = `<a-textarea v-model:value="model.${field.property}" :rows="3" :auto-size="{ minRows: 3, maxRows: 8 }"${field.length !== undefined ? ` :maxlength="${field.length}" show-count` : ""} />`;
      break;
    case "int":
    case "long":
      control = `<a-input-number v-model:value="model.${field.property}" :precision="0"${field.range?.min !== undefined ? ` :min="${field.range.min}"` : ""}${field.range?.max !== undefined ? ` :max="${field.range.max}"` : ""} class="number-control" />`;
      break;
    case "decimal":
      control = `<a-input-number v-model:value="model.${field.property}" string-mode :precision="${field.scale ?? 0}"${field.range?.min !== undefined ? ` :min="${field.range.min}"` : ""}${field.range?.max !== undefined ? ` :max="${field.range.max}"` : ""} class="number-control" />`;
      break;
    case "bool":
      control = `<a-checkbox v-model:checked="model.${field.property}">{{ t('${camel}.fields.${field.property}') }}</a-checkbox>`;
      break;
    case "date":
      control = `<a-date-picker v-model:value="model.${field.property}" :value-format="DATE_VALUE_FORMAT" />`;
      break;
    case "datetime":
      control = `<a-date-picker v-model:value="model.${field.property}" show-time :value-format="DATETIME_VALUE_FORMAT" />`;
      break;
    case "enum":
      control = `<a-select v-model:value="model.${field.property}" :options="options.${field.property}" />`;
      break;
    default:
      control = `<a-input v-model:value="model.${field.property}"${field.length !== undefined ? ` :maxlength="${field.length}"` : ""} />`;
  }
  return `${head}\n        ${control}\n      </a-form-item>`;
}

function ruleLines(field: NormalizedField, camel: string): string {
  const name = `t("${camel}.fields.${field.property}")`;
  const rules: string[] = [];
  if (field.required) rules.push(`{ required: true, message: t("${camel}.validation.required", { field: ${name} }) }`);
  if ((field.type === "string" || field.type === "text") && field.length !== undefined) {
    rules.push(`{ max: ${field.length}, message: t("${camel}.validation.maxLength", { field: ${name}, max: ${field.length} }) }`);
  }
  if ((field.type === "int" || field.type === "long") && field.range !== undefined) {
    rules.push(`{ type: "number" as const, min: ${field.range.min ?? "-Infinity"}, max: ${field.range.max ?? "Infinity"}, message: t("${camel}.validation.range", { field: ${name}, min: ${field.range.min ?? "—"}, max: ${field.range.max ?? "—"} }) }`);
  }
  return rules.length === 0 ? "" : `  ${field.property}: [${rules.join(", ")}],`;
}

function emptyValue(field: NormalizedField): string {
  if (field.type === "bool") return "false";
  if (field.type === "int" || field.type === "long") return "null";
  return "null";
}

