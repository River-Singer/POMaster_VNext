/**
 * scaffold-backend.spec.ts —— 后端层模板集 spring-mybatis-plus@1（11-01-storybook-scaffold S1-6）。
 *
 * 判据：
 * - 只认已定的技术基线：数据访问层是 MyBatis / MyBatis-Plus 才生成，语言 / 框架 / 数据库已定且不配套也不生成；
 * - Maven 多模块：父工程 + 领域核心 + 每个有暴露实体的面一个应用；项目自有模块只出种子（不受管）；
 * - 两个面的差异落到代码：管理侧每个接口声明规格里的权限码、OFFSET 分页、no-store、严格审计；
 *   用户侧每个接口声明访问档、KEYSET 分页、可见性与属主过滤写进查询、只出现暴露字段、匿名读可缓存；
 * - 字段分级落到代码：个人信息管理侧脱敏回显（提交脱敏值视为没改），敏感个人信息加密存储（AES-GCM）；
 * - 请求校验与接口文档同源（必填 / 长度 / 范围 / decimal 精度），错误体与接口文档 Problem 同形；
 * - 没有字符串拼接的 SQL（只用参数化的条件构造器）；
 * - 判卷：控制器与规格独立对照（权限码、访问档、接口数、用户侧视图字段）。
 */
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { load as loadYaml } from "js-yaml";
import { describe, expect, it } from "vitest";
import { loadCatalogArchetypes, resolveCatalogRoot } from "@pomaster/kernel";
import {
  BACKEND_TEMPLATE_SET,
  backendControllerPath,
  backendViewPath,
  checkBackendConformance,
  chooseBackendTemplateFromStack,
  renderBackend,
  validateDomainSpec,
  type NormalizedDomainSpec,
} from "@pomaster/cli";

const FLEET = fileURLToPath(new URL("../scaffold/examples/fleet.domain-spec.yaml", import.meta.url));
const SHOP = fileURLToPath(new URL("../scaffold/examples/shop.domain-spec.yaml", import.meta.url));
const CATALOG = loadCatalogArchetypes(resolveCatalogRoot()).map((material) => ({ id: material.id, operations: material.operations }));

function normalize(path: string): NormalizedDomainSpec {
  const result = validateDomainSpec(loadYaml(readFileSync(path, "utf8")), CATALOG);
  if (!result.ok || result.spec === null) throw new Error(`fixture spec invalid: ${JSON.stringify(result.issues.map((issue) => [issue.code, issue.path]))}`);
  return result.spec;
}

function files(spec: NormalizedDomainSpec): Map<string, string> {
  return new Map(renderBackend(spec).files.map((file) => [file.path, file.content]));
}

const JAVA = "backend/fleet-core/src/main/java/com/example/fleet";
const ADMIN = "backend/fleet-admin-api/src/main/java/com/example/fleet/adminapi";
const PUBLIC = "backend/fleet-public-api/src/main/java/com/example/fleet/publicapi";

describe("按技术基线选后端模板集", () => {
  const stack = (persistence: string | null, extra: Partial<Record<"language" | "framework" | "database", string>> = {}) =>
    chooseBackendTemplateFromStack({ language: null, framework: null, database: null, persistence, ...extra });

  it("数据访问层没定 → 不生成，指路 baseline set", () => {
    const choice = stack(null);
    expect(choice.kind).toBe("none");
    if (choice.kind === "none") expect(choice.hint).toContain("pomaster baseline set backend persistence");
    expect(stack("UNKNOWN").kind).toBe("none");
  });

  it("MyBatis / MyBatis-Plus → spring-mybatis-plus；语言、框架、数据库已定且配套也照样生成", () => {
    expect(stack("mybatis-plus").kind).toBe("spring-mybatis-plus");
    expect(stack("mybatis").kind).toBe("spring-mybatis-plus");
    expect(stack("mybatis-plus", { language: "java", framework: "spring", database: "mysql" }).kind).toBe("spring-mybatis-plus");
  });

  it("JPA、别的语言 / 框架 / 数据库 → 不生成，说明原因", () => {
    for (const choice of [
      stack("jpa"),
      stack("mybatis-plus", { language: "python" }),
      stack("mybatis-plus", { framework: "django" }),
      stack("mybatis-plus", { database: "postgresql" }),
    ]) {
      expect(choice.kind).toBe("none");
      if (choice.kind === "none") expect(choice.reason_zh).toMatch(/还没有后端模板/);
    }
  });
});

describe("渲染：模块布局与公共约定", () => {
  const spec = normalize(FLEET);
  const render = renderBackend(spec);
  const out = files(spec);

  it("确定性：同一规格两次渲染逐字节相同；路径排序、每个受管文件带生成头", () => {
    expect(renderBackend(spec)).toEqual(render);
    const paths = render.files.map((file) => file.path);
    expect(paths).toEqual([...paths].sort());
    for (const file of render.files) expect(file.content).toContain(`GENERATED by pomaster scaffold（${BACKEND_TEMPLATE_SET.id}@${BACKEND_TEMPLATE_SET.version}）`);
    expect(new Set(render.files.map((file) => file.keybindingSegment)).size).toBe(render.files.length);
  });

  it("Maven 多模块：父工程列出领域核心、项目扩展与两个应用；版本随模板集锁定", () => {
    const parent = out.get("backend/pom.xml")!;
    expect(parent).toContain("<artifactId>spring-boot-starter-parent</artifactId>");
    expect(parent).toContain("<version>4.1.1</version>");
    expect(parent).toContain("<artifactId>mybatis-plus-bom</artifactId>");
    expect([...parent.matchAll(/<module>([^<]+)<\/module>/g)].map((match) => match[1])).toEqual(["fleet-core", "fleet-support", "fleet-admin-api", "fleet-public-api"]);
    expect(out.get("backend/fleet-core/pom.xml")).toContain("<artifactId>mybatis-plus-spring-boot4-starter</artifactId>");
    expect(out.get("backend/fleet-admin-api/pom.xml")).toContain("<artifactId>spring-boot-starter-webmvc</artifactId>");
    expect(out.get("backend/fleet-public-api/pom.xml")).toContain("<artifactId>fleet-support</artifactId>");
  });

  it("项目自有模块只出种子：pom、扩展点说明、两份配置覆盖文件", () => {
    expect(render.seeds.map((seed) => seed.path)).toEqual([
      "backend/fleet-support/pom.xml",
      "backend/fleet-support/src/main/java/com/example/fleet/support/package-info.java",
      "backend/fleet-support/src/main/resources/support-admin.yml",
      "backend/fleet-support/src/main/resources/support-public.yml",
    ]);
    expect(render.files.some((file) => file.path.includes("fleet-support"))).toBe(false);
    expect(render.seeds[0]?.content).toContain("之后归项目所有");
  });

  it("应用配置：根路径取规格、管理端点独立端口（管理侧内网地址 / 用户侧只绑本机）、迁移不由应用账号跑", () => {
    const admin = out.get("backend/fleet-admin-api/src/main/resources/application.yml")!;
    const pub = out.get("backend/fleet-public-api/src/main/resources/application.yml")!;
    expect(admin).toContain("context-path: /admin/api/v1");
    expect(pub).toContain("context-path: /api/v1");
    expect(admin).toMatch(/port: 8081\n {4}address: \$\{FLEET_ADMIN_MANAGEMENT_ADDRESS:127\.0\.0\.1\}/);
    expect(pub).toMatch(/port: 8082\n {4}address: 127\.0\.0\.1/);
    expect(admin).toContain("import: optional:classpath:support-admin.yml");
    expect(admin).toContain("fail-on-unknown-properties: true");
    expect(admin).not.toContain("flyway");
    expect(out.get("backend/fleet-core/pom.xml")).toContain("<artifactId>flyway-maven-plugin</artifactId>");
    expect(admin).not.toMatch(/password: (?!\$\{)/);
  });

  it("没有字符串拼接的 SQL：只用参数化的条件构造器；分页、乐观锁、防全表更新插件都在", () => {
    for (const [path, text] of out) {
      if (!path.endsWith(".java")) continue;
      expect(text, path).not.toMatch(/\.last\(|@Select\(|@Update\(|@Insert\(|@Delete\(|\.apply\("[^"]*"\s*\+/);
    }
    const config = out.get(`${JAVA}/core/config/MybatisPlusConfig.java`)!;
    for (const name of ["PaginationInnerInterceptor(DbType.MYSQL)", "OptimisticLockerInnerInterceptor()", "BlockAttackInnerInterceptor()"]) expect(config).toContain(name);
  });
});

describe("渲染：两个面的差异落到代码", () => {
  const spec = normalize(FLEET);
  const out = files(spec);
  const adminController = out.get(`${ADMIN}/web/VehicleModelAdminController.java`)!;
  const publicController = out.get(`${PUBLIC}/web/VehicleModelPublicController.java`)!;

  it("管理侧：每个接口声明规格里的权限码；没声明权限码的接口一律拒绝", () => {
    const codes = [...adminController.matchAll(/@RequirePermission\("([^"]+)"\)/g)].map((match) => match[1]);
    expect(codes).toEqual(["fleet:vehicle_model:list", "fleet:vehicle_model:get", "fleet:vehicle_model:create", "fleet:vehicle_model:update", "fleet:vehicle_model:delete"]);
    const interceptor = out.get(`${ADMIN}/web/PermissionInterceptor.java`)!;
    expect(interceptor).toContain('throw new ForbiddenException("接口没有声明权限码")');
    expect(interceptor).toContain("actors.require()");
    expect(out.get(`${ADMIN}/web/NoStoreFilter.java`)).toContain('"no-store"');
  });

  it("管理侧：OFFSET 分页（页长上限 200）、总数按实体开启、写操作严格审计、数据范围走扩展点", () => {
    expect(adminController).toContain('@RequestParam(name = "size", defaultValue = "20") @Min(1) @Max(200) int size');
    expect(adminController).toContain("service.listPage(filter, page, size, true, scope(actor))");
    expect(adminController).toContain("AuditLevel.STRICT");
    expect(adminController).toContain("dataScopes.restrict(ENTITY, query, actor)");
    expect(out.get(`${ADMIN}/dto/VehicleModelPage.java`)).toContain("boolean hasMore, long total");
  });

  it("用户侧：访问档、KEYSET 分页（页长上限 50）、可见性条件写进每条查询、匿名读可缓存并带 ETag", () => {
    expect([...publicController.matchAll(/@Access\(AccessLevel\.([A-Z]+)\)/g)].map((match) => match[1])).toEqual(["ANONYMOUS", "ANONYMOUS"]);
    expect(publicController).toContain('@RequestParam(name = "limit", defaultValue = "20") @Min(1) @Max(50) int limit');
    expect(publicController).toContain("query.in(VehicleModel::getStatus, List.of(VehicleModelStatus.ENABLED));");
    expect(publicController).toContain("service.listAfter(filter, after, limit, scope())");
    expect(publicController).toContain("service.get(id, scope())");
    expect(publicController).toContain(".cacheControl(anonymousRead)");
    expect(publicController).not.toContain("Actors");
    expect(out.get(`${PUBLIC}/web/WebConfig.java`)).toContain("new ShallowEtagHeaderFilter()");
    expect(out.get(`${PUBLIC}/web/AccessInterceptor.java`)).toContain('throw new ForbiddenException("接口没有声明访问档")');
  });

  it("用户侧只出现对用户侧暴露的字段：视图与检索参数都不带成本价、状态", () => {
    const view = out.get(`${PUBLIC}/dto/PublicVehicleModelView.java`)!;
    expect(view).toContain("String businessCode");
    expect(view).not.toMatch(/costPrice|\bstatus\b|createdBy/);
    expect(publicController).not.toMatch(/name = "status"/);
    expect(out.get(`${ADMIN}/dto/VehicleModelView.java`)).toContain("String costPrice");
  });

  it("请求校验与接口文档同源：必填、长度、范围、decimal 精度；修改带 version", () => {
    const create = out.get(`${ADMIN}/dto/VehicleModelCreateRequest.java`)!;
    expect(create).toContain("@NotBlank @Size(max = 32) String businessCode");
    expect(create).toContain("@NotNull VehicleModelStatus status");
    expect(create).toContain("@Min(1) @Max(99) Integer seats");
    expect(create).toContain('@Pattern(regexp = "^-?\\\\d{1,10}(\\\\.\\\\d{1,2})?$") @DecimalMin("0") String listPrice');
    expect(out.get(`${ADMIN}/dto/VehicleModelUpdateRequest.java`)).toContain("@NotNull @Min(0) Integer version");
  });

  it("错误体与接口文档 Problem 同形：code / trace_id / field_errors[{detail, pointer}]，problem+json", () => {
    const problem = out.get(`${ADMIN}/web/ApiProblem.java`)!;
    expect(problem).toContain("String trace_id");
    expect(problem).toContain("List<FieldViolation> field_errors");
    expect(problem).toContain("record FieldViolation(String detail, String pointer)");
    const handler = out.get(`${ADMIN}/web/ProblemHandler.java`)!;
    expect(handler).toContain("MediaType.APPLICATION_PROBLEM_JSON");
    expect(handler).toContain("HttpStatus.TOO_MANY_REQUESTS");
    expect(handler).toContain("HttpHeaders.RETRY_AFTER");
    expect(handler).toContain('"INTERNAL_ERROR", "服务内部错误，请凭 trace_id 联系管理员"');
    expect(handler).not.toContain("getStackTrace");
  });

  it("用例服务：一次写一个库事务，版本不一致 409，唯一值冲突转字段级错误", () => {
    const service = out.get(`${JAVA}/core/service/VehicleModelService.java`)!;
    expect(service.match(/@Transactional\n/g)?.length).toBe(3);
    expect(service).toContain("throw new VersionConflictException(ENTITY, id);");
    expect(service).toContain('throw new DuplicateValueException("businessCode", "车型编码已存在");');
    expect(service).toContain('message.contains("uk_vehicle_model_business_code")');
    expect(service).toContain("query.and(w -> w.gt(VehicleModel::getBusinessCode, value).or(x -> x.eq(VehicleModel::getBusinessCode, value).gt(VehicleModel::getId, lastId)));");
  });
});

describe("渲染：属主实体与字段分级", () => {
  const spec = normalize(SHOP);
  const out = files(spec);
  const core = "backend/shop-ops-core/src/main/java/com/example/shop/core";
  const admin = "backend/shop-ops-admin-api/src/main/java/com/example/shop/adminapi";
  const pub = "backend/shop-ops-public-api/src/main/java/com/example/shop/publicapi";

  it("属主档：用户侧增删改查都按 owner_id 过滤，新建时属主取操作者；写操作基础审计", () => {
    const controller = out.get(`${pub}/web/CustomerAddressPublicController.java`)!;
    const entity = spec.entities.find((candidate) => candidate.key === "customer_address")!;
    expect(checkBackendConformance(entity, "public", controller, out.get(`${pub}/dto/PublicCustomerAddressView.java`)!)).toEqual([]);
    expect(checkBackendConformance(entity, "public", controller.replace("query.eq(CustomerAddress::getOwnerId, actor.userId());", ""), null)).toEqual(["属主过滤不在场（owner_id = 操作者）"]);
    expect([...controller.matchAll(/@Access\(AccessLevel\.([A-Z]+)\)/g)].map((match) => match[1])).toEqual(["OWNER", "OWNER", "OWNER", "OWNER", "OWNER"]);
    expect(controller).toContain("query.eq(CustomerAddress::getOwnerId, actor.userId());");
    expect(controller).toContain("draft.setOwnerId(actor.userId());");
    expect(controller).toContain("AuditLevel.BASIC");
    expect(controller).toContain('header(HttpHeaders.CACHE_CONTROL, "private, no-store")');
  });

  it("个人信息：管理侧视图脱敏，修改时提交脱敏回显值视为没改；审计快照脱敏、敏感个人信息不记值", () => {
    expect(out.get(`${admin}/dto/CustomerAddressView.java`)).toContain("Masking.mask(row.getReceiver())");
    expect(out.get(`${pub}/dto/PublicCustomerAddressView.java`)).not.toContain("Masking");
    const update = out.get(`${admin}/dto/CustomerAddressUpdateRequest.java`)!;
    expect(update).toContain("if (!Masking.isMaskOf(receiver, row.getReceiver())) {");
    const service = out.get(`${core}/service/CustomerAddressService.java`)!;
    expect(service).toContain('out.put("receiver", Masking.maskAny(row.getReceiver()));');
    expect(service).toContain('out.put("phone", row.getPhone() == null ? null : "[encrypted]");');
  });

  it("敏感个人信息加密存储：实体列挂加密类型处理器，AES-GCM，密钥从配置注入、没配启动即失败", () => {
    const entity = out.get(`${core}/entity/CustomerAddress.java`)!;
    expect(entity).toContain("@TableField(value = \"`phone`\", updateStrategy = FieldStrategy.ALWAYS, typeHandler = EncryptedTypeHandler.class)");
    expect(entity).toContain("@TableField(value = \"`birthday`\", updateStrategy = FieldStrategy.ALWAYS, typeHandler = EncryptedTypeHandler.class)");
    const cipher = out.get(`${core}/crypto/FieldCipher.java`)!;
    expect(cipher).toContain('Cipher.getInstance("AES/GCM/NoPadding")');
    expect(cipher).toContain("private static final int IV_BYTES = 12;");
    expect(cipher).toContain("if (raw.length != 32)");
    expect(out.get("backend/shop-ops-admin-api/src/main/resources/application.yml")).toContain("key: ${SHOP_OPS_FIELD_KEY:}");
    expect(files(normalize(FLEET)).has(`${JAVA}/core/crypto/FieldCipher.java`)).toBe(false);
  });

  it("可空排序键的 KEYSET：降序时空值段在后、升序时空值段在前", () => {
    const desc = out.get(`${core}/service/CustomerAddressService.java`)!;
    expect(desc).toContain("query.and(w -> w.isNull(CustomerAddress::getLabel).lt(CustomerAddress::getId, lastId));");
    expect(desc).toContain(".or(x -> x.isNull(CustomerAddress::getLabel)));");
    const asc = out.get(`${core}/service/NoticeService.java`)!;
    expect(asc).toContain("query.and(w -> w.isNull(Notice::getPublishedOn).gt(Notice::getId, lastId).or(x -> x.isNotNull(Notice::getPublishedOn)));");
    expect(asc).toContain("LocalDate value = sortValue(cursor.value());");
  });

  it("只在用户侧暴露的实体不进管理侧应用；登录档的读由拦截器把关，不额外要操作者", () => {
    expect([...out.keys()].some((path) => path.startsWith(`${admin}/`) && path.includes("Tag"))).toBe(false);
    expect(out.has(`${pub}/web/TagPublicController.java`)).toBe(true);
    const notice = out.get(`${pub}/web/NoticePublicController.java`)!;
    expect(notice).toContain("@Access(AccessLevel.AUTHENTICATED)");
    expect(notice).not.toContain("Actors");
  });
});

