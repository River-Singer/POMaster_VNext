/**
 * scaffold-frontend.spec.ts —— 脚手架 S1-7：管理侧前端（vue-antd-admin@1）。
 *
 * 判据：
 * - 每个管理侧实体生成接口客户端、列表页、编辑抽屉（有新建或修改时）、路由、文案；公共文件各一份；
 * - 生成物照设计规范写：用 Ant Design 预设跑 `design check`，全部检查零违规；
 * - 界面文字只在文案字典里，路由按需加载并在 meta 声明权限码（与接口文档同源），接口路径取管理侧 base_path；
 * - 只读实体不生成编辑抽屉、没有操作列；只对用户侧暴露的实体不生成管理侧前端。
 */
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { load as loadYaml } from "js-yaml";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { loadCatalogArchetypes, resolveCatalogRoot } from "@pomaster/kernel";
import { assessDesignStandard, renderAdminFrontend, validateDomainSpec, type NormalizedDomainSpec } from "@pomaster/cli";

const SAMPLE_PATH = fileURLToPath(new URL("../scaffold/examples/fleet.domain-spec.yaml", import.meta.url));
const CATALOG = loadCatalogArchetypes(resolveCatalogRoot()).map((material) => ({ id: material.id, operations: material.operations }));

// eslint-disable-next-line @typescript-eslint/no-explicit-any
type Raw = Record<string, any>;

function sampleRaw(): Raw {
  return loadYaml(readFileSync(SAMPLE_PATH, "utf8")) as Raw;
}

function normalize(raw: Raw): NormalizedDomainSpec {
  const result = validateDomainSpec(raw, CATALOG);
  if (!result.ok || result.spec === null) throw new Error(JSON.stringify(result.issues.slice(0, 3)));
  return result.spec;
}

let dir: string;

beforeEach(() => {
  dir = mkdtempSync(join(tmpdir(), "scaffold-frontend-"));
});

afterEach(() => {
  rmSync(dir, { recursive: true, force: true });
});

function writeAll(spec: NormalizedDomainSpec): Map<string, string> {
  const files = new Map<string, string>();
  for (const file of renderAdminFrontend(spec)) {
    const target = join(dir, file.path);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, file.content, "utf8");
    files.set(file.path, file.content);
  }
  return files;
}

describe("管理侧前端生成", () => {
  it("每个实体：接口客户端、列表、编辑抽屉、路由、文案；公共文件各一份", () => {
    const files = renderAdminFrontend(normalize(sampleRaw()));
    expect(files.map((file) => [file.path, file.template])).toEqual([
      ["frontend/admin/src/api/http.ts", "vue.admin.http"],
      ["frontend/admin/src/utils/format.ts", "vue.admin.format"],
      ["frontend/admin/src/auth/permission.ts", "vue.admin.permission"],
      ["frontend/admin/src/locales/zh-CN/index.ts", "vue.admin.locale-index"],
      ["frontend/admin/src/router/scaffold.ts", "vue.admin.routes-index"],
      ["frontend/admin/src/locales/zh-CN/vehicle-model.ts", "vue.admin.locale"],
      ["frontend/admin/src/api/vehicle-model.ts", "vue.admin.api"],
      ["frontend/admin/src/views/vehicle-model/VehicleModelList.vue", "vue.admin.list"],
      ["frontend/admin/src/router/vehicle-model.ts", "vue.admin.routes"],
      ["frontend/admin/src/views/vehicle-model/VehicleModelForm.vue", "vue.admin.form"],
    ]);
    for (const file of files) expect(file.content).toContain("GENERATED by pomaster scaffold（vue-antd-admin@1）");
    // 确定性：两次生成逐字节一致
    expect(renderAdminFrontend(normalize(sampleRaw()))).toEqual(files);
  });

  it("生成物照设计规范写：Ant Design 预设的门禁全部零违规", () => {
    writeAll(normalize(sampleRaw()));
    const report = assessDesignStandard(dir, { roots: ["frontend/admin/src"] });
    if (!("checks" in report)) throw new Error(report.code);
    expect(report.files).toBe(10);
    expect(report.findings).toEqual([]);
    expect(report.violations).toBe(0);
    expect(report.checks.filter((check) => check.status === "failed")).toEqual([]);
    expect(report.checks.length).toBeGreaterThanOrEqual(30);
  });

  it("文案只在字典里；路由按需加载、meta 声明权限码；接口路径取管理侧 base_path；错误按 problem 归一", () => {
    const files = writeAll(normalize(sampleRaw()));
    const locale = files.get("frontend/admin/src/locales/zh-CN/vehicle-model.ts") ?? "";
    for (const text of ["车型编码", "名称", "状态", "座位数", "指导价", "成本价", "说明", "ENABLED: \"启用\"", "DISABLED: \"停用\"", "新建车型"]) {
      expect(locale).toContain(text);
    }
    const routes = files.get("frontend/admin/src/router/vehicle-model.ts") ?? "";
    expect(routes).toContain('component: () => import("@/views/vehicle-model/VehicleModelList.vue")');
    expect(routes).toContain('permission: "fleet:vehicle_model:list"');
    const api = files.get("frontend/admin/src/api/vehicle-model.ts") ?? "";
    expect(api).toContain('request<VehicleModelPage>("GET", "/vehicle-models"');
    expect(api).toContain("readonly total: number;");
    expect(api).toContain('readonly status: "ENABLED" | "DISABLED";');
    expect(api).toContain("readonly listPrice?: string | null;");
    expect(api).toContain('remove: (id: number, version: number) => request<void>("DELETE"');
    const http = files.get("frontend/admin/src/api/http.ts") ?? "";
    expect(http).toContain('export const API_BASE = "/admin/api/v1";');
    expect(http).toContain('credentials: "include"');
    expect(http).not.toMatch(/localStorage|sessionStorage/);
    const list = files.get("frontend/admin/src/views/vehicle-model/VehicleModelList.vue") ?? "";
    expect(list).toContain("pageSizeOptions: PAGE_SIZES");
    expect(list).toContain("router.replace");
    expect(list).toContain("controller?.abort()");
    expect(list).toContain("error.problem.status === 409");
    const form = files.get("frontend/admin/src/views/vehicle-model/VehicleModelForm.vue") ?? "";
    expect(form).toContain(":width=\"378\"");
    expect(form).toContain("version: props.record.version");
    expect(form).toContain('{ required: true, message: t("vehicleModel.validation.required"');
    expect(form).toContain(":max=\"99\"");
    expect(form).toContain("string-mode :precision=\"2\"");
  });

  it("只读实体没有编辑抽屉和操作列；只对用户侧暴露的实体不生成管理侧前端", () => {
    const readOnly = sampleRaw();
    readOnly["entities"][0]["exposure"]["admin"]["operations"] = ["list", "get"];
    const files = renderAdminFrontend(normalize(readOnly));
    expect(files.some((file) => file.template === "vue.admin.form")).toBe(false);
    const list = files.find((file) => file.template === "vue.admin.list")?.content ?? "";
    expect(list).not.toContain("column.key === 'actions'");
    expect(list).not.toContain("openCreate");

    const publicOnly = sampleRaw();
    delete publicOnly["entities"][0]["exposure"]["admin"];
    delete publicOnly["entities"][0]["archetypes"]["page"];
    delete publicOnly["surfaces"]["admin"];
    expect(renderAdminFrontend(normalize(publicOnly))).toEqual([]);
  });
});
